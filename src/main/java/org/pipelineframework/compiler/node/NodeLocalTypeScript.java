package org.pipelineframework.compiler.node;

import com.fasterxml.jackson.databind.ObjectMapper;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.util.List;
import java.util.Map;
import java.util.stream.Collectors;

/** Emits a typed binding to the execution runtime from an admitted Node projection. */
final class NodeLocalTypeScript {
    private final ObjectMapper json = new ObjectMapper();

    Map<String, String> render(NodeLocalProfile.Projection projection) throws IOException {
        String projectionJson = json.writerWithDefaultPrettyPrinter().writeValueAsString(projection) + "\n";
        String digest = NodeLocalCompiler.sha256(projectionJson.getBytes(StandardCharsets.UTF_8));
        return Map.of("projection.json", projectionJson, "models.ts", models(projection.types()),
            "application.ts", application(projection, projectionJson, digest));
    }

    private String models(List<NodeLocalProfile.Type> types) {
        StringBuilder source = new StringBuilder("""
            // Generated by the TPF Node LOCAL compiler.
            // The runtime validates the signed 32-bit integer range at invocation boundaries.
            export type Int32 = number;
            """);
        for (var type : types) {
            source.append("""

                export interface %s {
                  readonly value: Int32;
                }
                """.formatted(type.id()));
        }
        return source.toString();
    }

    private String application(NodeLocalProfile.Projection projection, String projectionJson, String digest)
        throws IOException {
        String stepIds = projection.steps().stream().map(step -> quote(step.id()))
            .collect(Collectors.joining(" | "));
        String handlers = projection.steps().stream()
            .map(step -> "  readonly " + quote(step.handler()) + ": Handler<Models." + step.inputType()
                + ", Models." + step.outputType() + ">;")
            .collect(Collectors.joining("\n"));
        return """
            // Generated by the TPF Node LOCAL compiler.
            import type * as Models from "./models.js";

            export type StepId = %s;
            export type ApplicationInput = Models.%s;
            export type ApplicationOutput = Models.%s;

            export interface InvocationContext {
              readonly executionId: string;
              readonly traceId: string;
            }

            export type Value<T> = { readonly kind: "VALUE"; readonly value: T };
            export type Handler<I, O> = (input: I, context: InvocationContext) => Value<O> | Promise<Value<O>>;

            export interface HandlerRegistry {
            %s
            }

            export type Failure = {
              readonly owner: "LOCAL_SHELL";
              readonly stepId: StepId;
            } & (
              | { readonly code: "TRANSIENT"; readonly message: string; readonly retryable: true }
              | { readonly code: "BUSINESS_REJECTION"; readonly message: string; readonly retryable: false }
              | { readonly code: "UNCLASSIFIED"; readonly message: "Unclassified business function failure"; readonly retryable: false }
            );

            // This is the shell's terminal record, independent of subscriber delivery.
            export type TerminalRecord =
              | { readonly kind: "COMPLETED"; readonly outcome: Value<ApplicationOutput> }
              | { readonly kind: "FAILED"; readonly failure: Failure }
              | { readonly kind: "REJECTED"; readonly diagnostic: string }
              | { readonly kind: "CANCELLED" };

            export interface Application {
              run(input: ApplicationInput, context: InvocationContext, signal?: AbortSignal): Promise<TerminalRecord>;
            }

            export interface RuntimeBinding {
              readonly schemaVersion: 1;
              readonly projectionJson: string;
              readonly projectionSha256: string;
              readonly handlers: HandlerRegistry;
            }

            export interface NodeLocalRuntime {
              // Validate the binding, projection bytes, required capabilities and handler registry
              // during load. The runtime owns validation and all execution policy after load.
              load(binding: RuntimeBinding): Application;
            }

            export const projectionJson = %s;
            export const projectionSha256 = "%s";

            export function createApplication(runtime: NodeLocalRuntime, handlers: HandlerRegistry): Application {
              return runtime.load({ schemaVersion: 1, projectionJson, projectionSha256, handlers });
            }
            """.formatted(stepIds, projection.pipeline().inputType(), projection.pipeline().outputType(),
                handlers, json.writeValueAsString(projectionJson), digest);
    }

    // Projection validation admits only ASCII identifiers for these quoted property names.
    private String quote(String name) {
        return "\"" + name + "\"";
    }
}
