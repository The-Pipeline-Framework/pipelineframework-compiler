package org.pipelineframework.compiler.polyglot;

import com.fasterxml.jackson.databind.ObjectMapper;
import java.io.IOException;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.regex.Pattern;
import java.util.stream.Collectors;

/** Emits Python source bindings and delegates all execution to the supplied runtime. */
final class PythonLocalSource {
    private static final Pattern TYPE_IDENTIFIER = Pattern.compile("[A-Za-z][A-Za-z0-9_]*");
    private static final Set<String> RESERVED_TYPE_NAMES = Set.of(("""
        False None True and as assert async await break class continue def del elif else except finally for from global
        if import in is lambda nonlocal not or pass raise return try while with yield
        """).strip().split("\\s+"));

    private final ObjectMapper json = new ObjectMapper();

    Map<String, String> render(LocalProfile.Projection projection, Path pipeline, String projectionJson,
                               String digest) throws IOException {
        for (var type : projection.types()) {
            if (!TYPE_IDENTIFIER.matcher(type.id()).matches() || RESERVED_TYPE_NAMES.contains(type.id())) {
                throw new IllegalArgumentException(pipeline + ".types." + type.id()
                    + " [TYPE_ID] canonical name cannot be used as a Python class declaration");
            }
        }
        return Map.of("models.py", models(projection.types()),
            "application.py", application(projection, projectionJson, digest));
    }

    private String models(List<LocalProfile.Type> types) {
        StringBuilder source = new StringBuilder("""
            # Generated by the TPF Python LOCAL compiler.
            # The runtime validates the signed 32-bit integer range at invocation boundaries.
            from builtins import int as _Int32
            from dataclasses import dataclass as _dataclass
            from typing import final as _final
            """);
        for (var type : types) {
            source.append("""


                @_final
                @_dataclass(frozen=True, slots=True)
                class %s:
                    value: _Int32
                """.formatted(type.id()));
        }
        return source.toString();
    }

    private String application(LocalProfile.Projection projection, String projectionJson, String digest)
        throws IOException {
        String stepIds = projection.steps().stream().map(step -> quote(step.id())).collect(Collectors.joining(", "));
        String boundaryTypes = projection.types().stream().map(type -> "_models." + type.id())
            .collect(Collectors.joining(" | "));
        String modelEntries = projection.types().stream()
            .map(type -> "    " + quote(type.id()) + ": _models." + type.id() + ",")
            .collect(Collectors.joining("\n"));
        String handlers = projection.steps().stream()
            .map(step -> "    " + quote(step.handler()) + ": Handler[_models." + step.inputType()
                + ", _models." + step.outputType() + "],")
            .collect(Collectors.joining("\n"));
        return """
            # Generated by the TPF Python LOCAL compiler.
            from collections.abc import Callable, Coroutine, Mapping
            from dataclasses import dataclass, field
            from types import MappingProxyType
            from typing import Any, Final, Generic, Literal, Protocol, TypeAlias, TypedDict, TypeVar, final, overload

            from . import models as _models

            StepId: TypeAlias = Literal[%s]
            ApplicationInput: TypeAlias = _models.%s
            ApplicationOutput: TypeAlias = _models.%s
            BoundaryValue: TypeAlias = %s


            @final
            @dataclass(frozen=True, slots=True)
            class InvocationContext:
                executionId: str
                traceId: str


            _I = TypeVar("_I")
            _O = TypeVar("_O", covariant=True)


            @final
            @dataclass(frozen=True, slots=True)
            class Value(Generic[_O]):
                value: _O
                kind: Literal["VALUE"] = field(init=False, default="VALUE")


            Handler: TypeAlias = Callable[
                [_I, InvocationContext], Value[_O] | Coroutine[Any, Any, Value[_O]]
            ]
            HandlerRegistry = TypedDict("HandlerRegistry", {
            %s
            })


            _FailureCode: TypeAlias = Literal["TRANSIENT", "BUSINESS_REJECTION", "UNCLASSIFIED"]


            @final
            @dataclass(frozen=True, slots=True)
            class Failure:
                step_id: StepId
                code: _FailureCode
                message: str
                retryable: bool
                owner: Literal["LOCAL_SHELL"] = field(init=False, default="LOCAL_SHELL")

                @overload
                def __init__(self, step_id: StepId, code: Literal["TRANSIENT"],
                             message: str, retryable: Literal[True]) -> None: ...

                @overload
                def __init__(self, step_id: StepId, code: Literal["BUSINESS_REJECTION"],
                             message: str, retryable: Literal[False]) -> None: ...

                @overload
                def __init__(self, step_id: StepId, code: Literal["UNCLASSIFIED"],
                             message: Literal["Unclassified business function failure"],
                             retryable: Literal[False]) -> None: ...

                def __init__(self, step_id: StepId, code: _FailureCode, message: str, retryable: bool) -> None:
                    if code not in ("TRANSIENT", "BUSINESS_REJECTION", "UNCLASSIFIED"):
                        raise ValueError("Unknown failure code")
                    if retryable is not (code == "TRANSIENT"):
                        raise ValueError("Only TRANSIENT failures must be retryable")
                    if code == "UNCLASSIFIED" and message != "Unclassified business function failure":
                        raise ValueError("UNCLASSIFIED failures require the fixed message")
                    object.__setattr__(self, "step_id", step_id)
                    object.__setattr__(self, "code", code)
                    object.__setattr__(self, "message", message)
                    object.__setattr__(self, "retryable", retryable)
                    object.__setattr__(self, "owner", "LOCAL_SHELL")


            @final
            @dataclass(frozen=True, slots=True)
            class Completed:
                outcome: Value[ApplicationOutput]
                kind: Literal["COMPLETED"] = field(init=False, default="COMPLETED")


            @final
            @dataclass(frozen=True, slots=True)
            class Failed:
                failure: Failure
                kind: Literal["FAILED"] = field(init=False, default="FAILED")


            @final
            @dataclass(frozen=True, slots=True)
            class Rejected:
                diagnostic: str
                kind: Literal["REJECTED"] = field(init=False, default="REJECTED")


            @final
            @dataclass(frozen=True, slots=True)
            class Cancelled:
                kind: Literal["CANCELLED"] = field(init=False, default="CANCELLED")


            # The runtime's terminal record is independent of subscriber delivery.
            TerminalRecord: TypeAlias = Completed | Failed | Rejected | Cancelled


            class CancellationSignal(Protocol):
                @property
                def cancelled(self) -> bool: ...

                def subscribe(self, callback: Callable[[], None], /) -> Callable[[], None]:
                    \"\"\"Notify inline on cancellation, including if already cancelled, and return unsubscribe.\"\"\"
                    ...


            class Application(Protocol):
                async def run(
                    self,
                    input: ApplicationInput,
                    context: InvocationContext,
                    signal: CancellationSignal | None = None,
                ) -> TerminalRecord: ...


            @final
            @dataclass(frozen=True, slots=True)
            class CarrierTypes:
                invocation_context: type[InvocationContext]
                value: type[Value[object]]
                failure: type[Failure]
                completed: type[Completed]
                failed: type[Failed]
                rejected: type[Rejected]
                cancelled: type[Cancelled]


            @final
            @dataclass(frozen=True, slots=True)
            class RuntimeBinding:
                projection_bytes: bytes
                projection_sha256: str
                model_types: Mapping[str, type[BoundaryValue]]
                carrier_types: CarrierTypes
                handlers: Mapping[str, object]
                schema_version: Literal[1] = field(init=False, default=1)


            class PythonLocalRuntime(Protocol):
                def load(self, binding: RuntimeBinding, /) -> Application:
                    \"\"\"Validate projection bytes, capabilities, nominal model identities and handlers before execution.\"\"\"
                    ...


            PROJECTION_BYTES: Final[bytes] = %s.encode("utf-8")
            PROJECTION_SHA256: Final[str] = "%s"
            _MODEL_TYPES: Final[Mapping[str, type[BoundaryValue]]] = MappingProxyType({
            %s
            })
            _CARRIER_TYPES: Final = CarrierTypes(InvocationContext, Value, Failure, Completed, Failed, Rejected, Cancelled)


            def create_application(runtime: PythonLocalRuntime, handlers: HandlerRegistry) -> Application:
                return runtime.load(RuntimeBinding(
                    PROJECTION_BYTES, PROJECTION_SHA256, _MODEL_TYPES, _CARRIER_TYPES, MappingProxyType(dict(handlers)),
                ))
            """.formatted(stepIds, projection.pipeline().inputType(), projection.pipeline().outputType(),
                boundaryTypes, handlers, json.writeValueAsString(projectionJson), digest, modelEntries);
    }

    // Projection validation admits ASCII step and handler identifiers.
    private String quote(String name) {
        return "\"" + name + "\"";
    }
}
