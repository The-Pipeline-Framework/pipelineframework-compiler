    private static String renderPyMetaDef(PipelineTemplateTypeDefinition def) {
        if (def instanceof PipelineTemplateTypeDefinition.RecordType record) {
            StringBuilder sb = new StringBuilder("{'kind': 'record', 'fields': {");
            List<PipelineTemplateTypeDefinition.Field> sorted = record.fields().stream()
                .sorted(Comparator.comparing(PipelineTemplateTypeDefinition.Field::name))
                .toList();
            for (int i = 0; i < sorted.size(); i++) {
                var f = sorted.get(i);
                if (i > 0) sb.append(", ");
                sb.append("'").append(escapePy(f.name())).append("': {'type': ")
                    .append(renderPyMetaRef(f.type())).append(", 'repeated': ")
                    .append(f.repeated() ? "True" : "False").append("}");
            }
            sb.append("}}");
            return sb.toString();
        }
        if (def instanceof PipelineTemplateTypeDefinition.WrapperType wrapper) {
            return "{'kind': 'wrapper', 'wraps': '" + escapePy(wrapper.wraps().name()) + "'}";
        }
        if (def instanceof PipelineTemplateTypeDefinition.AliasType alias) {
            return "{'kind': 'alias', 'target': " + renderPyMetaRef(alias.target()) + "}";
        }
        PipelineTemplateTypeDefinition.UnionType union = (PipelineTemplateTypeDefinition.UnionType) def;
        StringBuilder sb = new StringBuilder("{'kind': 'union', 'variants': {");
        List<PipelineTemplateTypeDefinition.Variant> sorted = union.variants().values().stream()
            .sorted(Comparator.comparing(PipelineTemplateTypeDefinition.Variant::discriminator))
            .toList();
        for (int i = 0; i < sorted.size(); i++) {
            var v = sorted.get(i);
            if (i > 0) sb.append(", ");
            sb.append("'").append(escapePy(v.discriminator())).append("': {'class': '")
                .append(escapePy(union.name() + "_" + toPascal(v.discriminator()))).append("', 'payload': ")
                .append(renderPyMetaRef(v.payload())).append("}");
        }
        sb.append("}}");
        return sb.toString();
    }

    private static String renderPyMetaRef(PipelineTemplateTypeReference ref) {
        if (ref instanceof PipelineTemplateTypeReference.Named named) {
            return "{'kind': 'named', 'id': '" + escapePy(named.name()) + "'}";
        }
        if (ref instanceof PipelineTemplateTypeReference.Scalar scalar) {
            return "{'kind': 'scalar', 'id': '" + escapePy(scalar.name()) + "'}";
        }
        if (ref instanceof PipelineTemplateTypeReference.MapType map) {
            return "{'kind': 'map', 'value': " + renderPyMetaRef(map.valueType()) + "}";
        }
        throw new IllegalArgumentException("Unsupported canonical type reference: " + ref);
    }

    private static String toPascal(String raw) {
        String camel = PolyglotCompiler.toCamelCase(raw);
        return Character.toUpperCase(camel.charAt(0)) + camel.substring(1);
    }

    private static String escapePy(String value) {
        return value.replace("\\", "\\\\").replace("'", "\\'");
    }
