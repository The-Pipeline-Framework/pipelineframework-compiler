    private static void renderTypeDefinition(StringBuilder sb, PipelineTemplateTypeDefinition def) {
        if (def instanceof PipelineTemplateTypeDefinition.RecordType record) {
            sb.append("export interface ").append(record.name()).append(" {\n");
            record.fields().stream()
                .sorted(Comparator.comparing(PipelineTemplateTypeDefinition.Field::name))
                .forEach(field -> {
                    String typeExpr = tsType(field.type());
                    if (field.repeated()) {
                        sb.append("  readonly ").append(field.name()).append(": readonly ")
                            .append(wrapIfUnion(typeExpr)).append("[];\n");
                    } else {
                        String opt = field.presence() == PipelineFieldPresence.OPTIONAL ? "?" : "";
                        String nul = field.nullability() == PipelineFieldNullability.NULLABLE ? " | null" : "";
                        sb.append("  readonly ").append(field.name()).append(opt).append(": ")
                            .append(typeExpr).append(nul).append(";\n");
                    }
                });
            sb.append("}\n");
        } else if (def instanceof PipelineTemplateTypeDefinition.WrapperType wrapper) {
            if (!wrapper.constraints().allowedValues().isEmpty()) {
                List<String> literals = new ArrayList<>();
                for (Object val : wrapper.constraints().allowedValues()) {
                    if (val instanceof String s) {
                        literals.add("'" + escapeJs(s) + "'");
                    } else if (val instanceof Number n) {
                        literals.add("int64".equals(wrapper.wraps().name()) ? n + "n" : n.toString());
                    } else if (val instanceof Boolean b) {
                        literals.add(b.toString());
                    }
                }
                if (!literals.isEmpty()) {
                    sb.append("export type ").append(wrapper.name()).append(" = ")
                        .append(String.join(" | ", literals)).append(";\n");
                    return;
                }
            }
            sb.append("export type ").append(wrapper.name()).append(" = ")
                .append(tsScalar(wrapper.wraps().name())).append(";\n");
        } else if (def instanceof PipelineTemplateTypeDefinition.AliasType alias) {
            sb.append("export type ").append(alias.name()).append(" = ")
                .append(tsType(alias.target())).append(";\n");
        } else if (def instanceof PipelineTemplateTypeDefinition.UnionType union) {
            sb.append("export type ").append(union.name()).append(" =\n");
            List<PipelineTemplateTypeDefinition.Variant> variants = union.variants().values().stream()
                .sorted(Comparator.comparing(PipelineTemplateTypeDefinition.Variant::discriminator))
                .toList();
            for (int i = 0; i < variants.size(); i++) {
                var v = variants.get(i);
                sb.append("  | { readonly discriminator: '").append(escapeJs(v.discriminator()))
                    .append("'; readonly value: ").append(tsType(v.payload())).append(" }");
                sb.append(i + 1 == variants.size() ? ";\n" : "\n");
            }
        }
    }

    private static String tsType(PipelineTemplateTypeReference ref) {
        if (ref instanceof PipelineTemplateTypeReference.Named named) {
            return named.name();
        }
        if (ref instanceof PipelineTemplateTypeReference.Scalar scalar) {
            return tsScalar(scalar.name());
        }
        if (ref instanceof PipelineTemplateTypeReference.MapType map) {
            return "Readonly<Record<string, " + tsType(map.valueType()) + ">>";
        }
        throw new IllegalArgumentException("Unsupported canonical type reference: " + ref);
    }

    private static String tsScalar(String name) {
        return switch (name) {
            case "bool" -> "boolean";
            case "int32", "float32", "float64" -> "number";
            case "int64" -> "Int64";
            case "decimal" -> "DecimalString";
            case "payload_ref" -> "PayloadRef";
            default -> "string";
        };
    }

    private static String wrapIfUnion(String expr) {
        return expr.contains(" | ") ? "(" + expr + ")" : expr;
    }

